# Modified: generated by agents-cli, then replaced the demo weather agent
# with the SF building-permit assistant (MCP tools, RAG, skills, guardrails).
"""San Francisco building-permit assistant (Google ADK + Gemini).

Tools come from three places:
* the MCP server ``mcp_server/server.py`` (discovered at runtime via McpToolset):
  search_permits (DataSF API), list_projects, get_project,
  create_submission_draft, send_submission;
* the RAG tool ``search_city_docs`` (Chroma + Gemini embeddings);
* ``activate_skill`` (skill registry).

The system prompt is rebuilt before every model call by the context builder
(``app.skills.build_instruction``); every tool call goes through the input
guardrails and every final answer through the output guardrail
(``app.guardrails``).
"""

import os
import sys

from google.adk.agents import Agent
from google.adk.apps import App
from google.adk.tools import FunctionTool
from google.adk.tools.mcp_tool.mcp_session_manager import StdioConnectionParams
from google.adk.tools.mcp_tool.mcp_toolset import McpToolset
from google.genai import types
from mcp import StdioServerParameters

from app import config
from app.guardrails import after_model, after_tool, before_tool
from app.rag import search_city_docs
from app.resilient_llm import make_model
from app.skills import activate_skill, build_instruction

MODEL = config.MODEL

mcp_tools = McpToolset(
    connection_params=StdioConnectionParams(
        server_params=StdioServerParameters(
            command=sys.executable,
            args=["-m", "mcp_server.server"],
            cwd=str(config.ROOT),
            env={**os.environ, "PYTHONPATH": str(config.ROOT)},
        ),
        timeout=30,
    ),
    tool_filter=[
        "search_permits",
        "list_projects",
        "get_project",
        "create_submission_draft",
        "send_submission",
    ],
)

root_agent = Agent(
    # Keep in sync with create_params.root_agent_name in agents-cli-manifest.yaml:
    # telemetry reports this name as gen_ai.agent.name, and agents-cli reports the
    # manifest's value. Renaming the agent only here makes the two disagree, and
    # anything selecting traces by name stops finding this agent's.
    name="sf_permit_assistant",
    # Free tier: short time budget per model, then automatic fallback to the
    # next free Gemini model (app.resilient_llm) instead of minutes of retries.
    model=make_model(MODEL),
    description="Assistant permis de construire à San Francisco : permis existants, documents requis, dossiers.",
    instruction=build_instruction,  # context builder (InstructionProvider)
    tools=[FunctionTool(activate_skill), FunctionTool(search_city_docs), mcp_tools],
    before_tool_callback=before_tool,
    after_tool_callback=after_tool,
    after_model_callback=after_model,  # output guardrail: disclaimer + sources
    generate_content_config=types.GenerateContentConfig(temperature=0),
)

app = App(
    root_agent=root_agent,
    name="app",
)
